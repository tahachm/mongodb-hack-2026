export type LlmProvider = 'gemini' | 'anthropic'

function requireEnv(name: string): string {
  const value = process.env[name]
  if (!value) {
    throw new Error(`${name} env var is required`)
  }
  return value
}

/** Parses `MERCHANT_URLS=mall-wart=http://127.0.0.1:8080,somefrills=http://127.0.0.1:8082`
 * into an id -> base URL map. Empty/unset is valid -- shopping tools just report "no
 * merchants configured" instead of the server refusing to start, so plain chat still works
 * without any merchant/psp processes running. */
function parseMerchantUrls(raw: string | undefined): Map<string, string> {
  const merchants = new Map<string, string>()
  if (!raw) return merchants
  for (const pair of raw.split(',')) {
    const [id, url] = pair.split('=').map((s) => s.trim())
    if (id && url) merchants.set(id, url.replace(/\/$/, ''))
  }
  return merchants
}

const provider: LlmProvider = process.env.LLM_PROVIDER === 'anthropic' ? 'anthropic' : 'gemini'

export const config = {
  port: Number(process.env.PORT) || 4000,
  provider,
  // Only the active provider's key is required -- picking Gemini shouldn't force you to also
  // set up an Anthropic Console account, and vice versa.
  gemini: {
    apiKey:
      provider === 'gemini' ? requireEnv('GEMINI_API_KEY') : (process.env.GEMINI_API_KEY ?? ''),
    model: process.env.GEMINI_MODEL ?? 'gemini-3.5-flash-lite',
  },
  anthropic: {
    apiKey:
      provider === 'anthropic'
        ? requireEnv('ANTHROPIC_API_KEY')
        : (process.env.ANTHROPIC_API_KEY ?? ''),
    model: process.env.ANTHROPIC_MODEL ?? 'claude-haiku-5-5',
    // See DEFAULT_MAX_TOKENS in claude.ts for why the default is well above 1024: large
    // record_audit_event tool calls were getting truncated mid-JSON at the old cap.
    maxTokens: Number(process.env.ANTHROPIC_MAX_TOKENS) || undefined,
  },
  merchants: parseMerchantUrls(process.env.MERCHANT_URLS),
  pspUrl: (process.env.PSP_URL ?? 'http://127.0.0.1:8081').replace(/\/$/, ''),
  // Raw transcript dump for auditing: after a purchase completes, the *entire* conversation
  // that led to it (every turn, including tool_call requests and tool_result responses, not
  // just the final text) is written to this collection. Separate from preferences'
  // purchase_vectors -- that's semantic recall for the agent; this is an unprocessed audit
  // record. Unset MONGODB_URI is valid, same graceful-degradation story as MERCHANT_URLS --
  // the dump is just skipped (and logged) rather than the server refusing to start.
  mongoUri: process.env.MONGODB_URI,
  mongoDb: process.env.MONGODB_DB ?? 'agentic_commerce',
  transcriptsCollection: process.env.TRANSCRIPTS_COLLECTION ?? 'conversation_transcripts',
  // record_history_insights/record_recommendation_plan's backing store -- the `audit_events`
  // collection from plan/PLAN.md section 5.2 (see agent-system-prompt.md's header comment).
  // Unlike MONGODB_URI above being optional for the transcript dump, these tools have no
  // graceful-degradation path: the tools throw when unset, since an audit trail that
  // silently doesn't exist is worse
  // than one that visibly fails -- see auditEvents.ts.
  auditEventsCollection: process.env.AUDIT_EVENTS_COLLECTION ?? 'audit_events',
  // Vector embeddings for search_preferences / save_preference_record are generated by
  // MongoDB Atlas Vector Search's Automated Embedding (Voyage AI), entirely server-side -- we
  // only ever send/receive raw text, never call an embedding API ourselves. See preferences/.
  preferencesUrl: (process.env.PREFERENCES_URL ?? 'http://127.0.0.1:8083').replace(/\/$/, ''),
}
