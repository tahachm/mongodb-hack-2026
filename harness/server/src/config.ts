export type LlmProvider = 'gemini' | 'anthropic'

function requireEnv(name: string): string {
  const value = process.env[name]
  if (!value) {
    throw new Error(`${name} env var is required`)
  }
  return value
}

/** Parses `MERCHANT_URLS=mall-wart=http://127.0.0.1:8080,somefrills=http://127.0.0.1:8082`
 * into an id -> base URL map. Empty/unset is valid -- shopping tools just report "no
 * merchants configured" instead of the server refusing to start, so plain chat still works
 * without any merchant/psp processes running. */
function parseMerchantUrls(raw: string | undefined): Map<string, string> {
  const merchants = new Map<string, string>()
  if (!raw) return merchants
  for (const pair of raw.split(',')) {
    const [id, url] = pair.split('=').map((s) => s.trim())
    if (id && url) merchants.set(id, url.replace(/\/$/, ''))
  }
  return merchants
}

const provider: LlmProvider = process.env.LLM_PROVIDER === 'anthropic' ? 'anthropic' : 'gemini'

export const config = {
  port: Number(process.env.PORT) || 4000,
  provider,
  // Only the active provider's key is required -- picking Gemini shouldn't force you to also
  // set up an Anthropic Console account, and vice versa.
  gemini: {
    apiKey:
      provider === 'gemini' ? requireEnv('GEMINI_API_KEY') : (process.env.GEMINI_API_KEY ?? ''),
    model: process.env.GEMINI_MODEL ?? 'gemini-3.5-flash-lite',
  },
  anthropic: {
    apiKey:
      provider === 'anthropic'
        ? requireEnv('ANTHROPIC_API_KEY')
        : (process.env.ANTHROPIC_API_KEY ?? ''),
    model: process.env.ANTHROPIC_MODEL ?? 'claude-haiku-5-5',
  },
  merchants: parseMerchantUrls(process.env.MERCHANT_URLS),
  pspUrl: (process.env.PSP_URL ?? 'http://127.0.0.1:8081').replace(/\/$/, ''),
  // Vector embeddings for pay_for_checkout_session / recall_past_purchases are generated by
  // MongoDB Atlas Vector Search's Automated Embedding (Voyage AI), entirely server-side -- we
  // only ever send/receive raw text, never call an embedding API ourselves. See preferences/.
  preferencesUrl: (process.env.PREFERENCES_URL ?? 'http://127.0.0.1:8083').replace(/\/$/, ''),
}
